// Fallback for heroes som ikke er i listen over (f.eks. nye heroes).
export function guessPositions(roles = []) {
  const r = new Set(roles);
  const out = [];
  if (r.has('Carry')) out.push(1);
  if (r.has('Carry') && r.has('Nuker')) out.push(2);
  if (r.has('Initiator') || r.has('Durable')) out.push(3);
  if (r.has('Support')) out.push(4, 5);
  return out.length ? out : [1, 2, 3, 4, 5];
}

export function positionsFor(hero) {
  return POSITIONS[hero.name] || guessPositions(hero.roles);
}
